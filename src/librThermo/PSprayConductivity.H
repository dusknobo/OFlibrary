// Source: ASHRAE 526-RP Eq 12, PDF p21 coefficient table. T K, X kg/kg.
// lambda fit valid 20-190 C, 30-65%; dilute bridge to HEOS is explicit.
// Caller audits all physical concentrated-liquid temperatures >=293.15 K.
/**
 * @file PSprayConductivity.H
 * @brief ASHRAE 526-RP导热系数关联式与稀溶液过渡，输出W/(m·K)。
 *
 * 关联式的x为质量百分数；函数输入X为质量分数，内部乘100转换。
 * X<0.30时显式线性连接纯水值与30%溶液值，属于当前模型假设。
 * 浓溶液的有效温度检查及数值尾迹标记由LiBrSolutionProperties完成。
 */
#ifndef PSprayConductivity_H
#define PSprayConductivity_H
#include <cmath>
#include <algorithm>

namespace librSpray
{
inline double conductivity(double T, double X)
{
    // 纯水参考表：278.15—353.15 K，间隔1 K；下面对表端点作有界处理。
    static const double kw[76] = {
        0.5677233028454152, 0.5700065531780063, 0.5722453990013866, 0.5744415363167676,
        0.5765965528722445, 0.5787119359406184, 0.5807890794622163, 0.5828292906136114,
        0.5848337958557267, 0.5868037465097727, 0.5887402239031463, 0.5906442441242959,
        0.5925167624202741, 0.594358677268237,  0.5961708341480971, 0.5979540290420151,
        0.5997090116824189, 0.6014364885698078, 0.6031371257780628, 0.6048115515646968,
        0.6064603588007343, 0.6080841072343626, 0.6096833256010959, 0.6112585135917912,
        0.6128101436891613, 0.6143386628823538, 0.6158444942686678, 0.6173280385503315,
        0.6187896754338382, 0.6202297649387853, 0.6216486486224141, 0.6230466507258605,
        0.6244240792472316, 0.6257812269467463, 0.6271183722882856, 0.6284357803217918,
        0.629733703510256,  0.6310123825051743, 0.6322720468735271, 0.63351291577979,
        0.6347351986255878, 0.6359390956498067, 0.6371247984917006, 0.6382924907193837,
        0.6394423483256985, 0.6405745401936896, 0.6416892285335538, 0.6427865692926675,
        0.6438667125406076, 0.6449298028304675, 0.6459759795380292, 0.6470053771802253,
        0.6480181257138674, 0.6490143508161973, 0.6499941741480451, 0.6509577136008268,
        0.6519050835282464, 0.6528363949637078, 0.6537517558241753, 0.6546512711013955,
        0.6555350430411803, 0.6564031713114121, 0.6572557531595882, 0.6580928835602576,
        0.6589146553533154, 0.6597211593732835, 0.6605124845705178, 0.6612887181243891,
        0.6620499455493493, 0.6627962507939327, 0.6635277163333378, 0.6642444232558858,
        0.6649464513436953, 0.665633879147973,  0.6663067840592174, 0.6669652423725836};
    const double u = std::max(0., std::min(75., T - 278.15));
    const int i = std::min(74, int(u));
    const double water = kw[i] + (kw[i + 1] - kw[i]) * (u - i);
    // 先在至少30%处计算浓溶液关联式；稀溶液随后从纯水值插值过渡。
    const double x = 100 * std::max(.3, X);
    const double k = ((-1407.5255 + 11.051253 * T - 1.4674147e-2 * T * T) +
                      (38.985550 - .24047484 * T + 3.4807273e-4 * T * T) * x +
                      (-.26502516 + 1.5191536e-3 * T - 2.3226242e-6 * T * T) * x * x) /
                     1000.;
    // 原始多项式单位为mW/(m·K)，上式除1000后统一为SI单位。
    return X >= .3 ? k : water + (k - water) * (X / .3);
}
}
#endif
